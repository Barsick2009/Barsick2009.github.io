export function svcInfo(name) {
  const n = String(name || '').toLowerCase(), k = svcKind(name), base = INFO[k] || INFO.shine;
  const lt = LIGHT.find(([re]) => re.test(n)); if (lt) return lt[1];
  if (k !== 'drops') return base;
  // мойки различаются составом — уточняем по названию
  if (/экспресс|бесконтакт/.test(n)) return { inc: ['Бесконтактная мойка активной пеной', 'Ополаскивание', 'Сушка кузова'], plus: ['Быстро — без долгого ожидания', 'Смывает дорожную грязь и реагенты', 'Бережно к покрытию'] };
  if (/детейлинг/.test(n)) return { inc: ['Двухфазная мойка: предварительная и основная', 'Ручная мойка кузова безопасным методом', 'Чистка дисков, арок, проёмов дверей', 'Удаление следов насекомых и битума', 'Сушка микрофиброй и мягким воздухом'], plus: ['Максимально бережно к лаку — без микроцарапин', 'Чистые даже труднодоступные места', 'Отличная подготовка к полировке и защите'] };
  if (/комплекс/.test(n)) return { inc: [...base.inc, 'Уборка салона пылесосом', 'Протирка пластика и стёкол внутри', 'Чистка ковриков'], plus: ['Чисто и снаружи, и внутри за один визит', ...base.plus.slice(0, 2)] };
  return base;
}
